const merge = (base: LocaleMessage, override: LocaleMessage): LocaleMessage => {
    const result: LocaleMessage = { ...base };
    for (const [key, value] of Object.entries(override)) {
        if (value && typeof value === 'object' && !Array.isArray(value) && result[key] && typeof result[key] === 'object') {
            result[key] = merge(result[key] as LocaleMessage, value as LocaleMessage);
        } else {
            result[key] = value;
        }
    }
    return result;
};

export const getServerPageLocaleMessage = (locale: string): LocaleMessage => {
    return merge(common, localized[locale] || {});
};

export const serverPageMessage = common;
